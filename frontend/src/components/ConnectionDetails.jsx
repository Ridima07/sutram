
import { useState } from "react";

function formatTimestamp(timestamp) {
  if (!timestamp) return "Not available";

  const date = new Date(timestamp);

  if (Number.isNaN(date.getTime())) return "Not available";

  return date.toLocaleString("en-IN", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
  });
}

function ComputedConnectionDetails({ edge }) {
  const { data } = edge;
  const [showTrace, setShowTrace] = useState(false);

  const recordIds = data.recordIds ?? [];
  const sharedEntities = data.sharedEntities ?? [];

  return (
    <div className="details-content">
      <div className="details-header">
        <span className="eyebrow">COMPUTED CORRELATION</span>
        <h2>{edge.label || "Corroborated activity"}</h2>
        <p className="entity-description">
          This relationship was generated by the cross-source
          correlation pipeline, not manually added as a mock edge.
        </p>
      </div>

      <div className="connection-path">
        <div>
          <span className="path-label">SOURCE ENTITY</span>
          <strong>{edge.source}</strong>
        </div>

        <span className="large-arrow">→</span>

        <div>
          <span className="path-label">RELATED ENTITY</span>
          <strong>{edge.target}</strong>
        </div>
      </div>

      <div className="explanation-box">
        <span className="eyebrow">WHY ARE THESE CONNECTED?</span>
        <p>{data.reason || "The correlation pipeline matched these records."}</p>
      </div>

      <div className="evidence-section">
        <div className="section-title">
          <h3>Correlation Results</h3>
          <span className="verified-badge">
            {data.strength?.toUpperCase() || "UNKNOWN"}
          </span>
        </div>

        <div className="detail-card">
          <span>CORRELATION TYPE</span>
          <strong>{data.relation || "Not available"}</strong>
        </div>

        <div className="detail-card">
          <span>TIME DIFFERENCE</span>
          <strong>
            {data.timeDifferenceSeconds == null
              ? "Not available"
              : `${data.timeDifferenceSeconds} seconds`}
          </strong>
        </div>

        <div className="detail-card">
          <span>SUPPORTING RECORDS</span>
          <strong>{recordIds.length}</strong>
        </div>
      </div>

      <div className="evidence-section">
        <div className="section-title">
          <h3>Correlated Record IDs</h3>
          <span>{recordIds.length}</span>
        </div>

        {recordIds.length === 0 ? (
          <p className="muted">No record IDs supplied.</p>
        ) : (
          recordIds.map((recordId) => (
            <div className="detail-card" key={recordId}>
              <span>EVIDENCE RECORD</span>
              <strong>{recordId}</strong>
            </div>
          ))
        )}
      </div>

      <div className="evidence-section">
        <div className="section-title">
          <h3>Shared Entities</h3>
          <span>{sharedEntities.length}</span>
        </div>

        {sharedEntities.length === 0 ? (
          <p className="muted">No shared entities supplied.</p>
        ) : (
          <div className="connection-list">
            {sharedEntities.map((entity) => (
              <div className="connection-item" key={entity}>
                <strong>{entity}</strong>
              </div>
            ))}
          </div>
        )}
      </div>

      <button
        className="trace-button"
        onClick={() => setShowTrace(!showTrace)}
      >
        {showTrace ? "Hide Correlation Trace" : "View Correlation Trace"}
      </button>

      {showTrace && (
        <div className="trace-panel">
          <span className="eyebrow">CORRELATION TRACE</span>

          {recordIds.map((recordId, index) => (
            <div key={recordId}>
              <div className="trace-node">
                <span>{index + 1}</span>
                <strong>{recordId}</strong>
                <small>FORENSIC RECORD</small>
              </div>

              {index < recordIds.length - 1 && (
                <div className="trace-line" />
              )}
            </div>
          ))}

          <p className="trace-note">
            These records were matched by the correlation pipeline.
            The shared entities and time difference explain the match.
          </p>
        </div>
      )}

      <div className="audit-note">
        <span>✓</span>
        <div>
          <strong>Computed evidence correlation</strong>
          <p>
            This relationship was generated from the pipeline's
            matched records. Correlation indicates supporting evidence,
            not proof of wrongdoing by itself.
          </p>
        </div>
      </div>
    </div>
  );
}

